//! LZ77 symbol utilities from `src/zopfli/symbols.h`.
//!
//! Distance helpers use the `__builtin_clz` formulas (`ZOPFLI_HAS_BUILTIN_CLZ`).
//! `31 ^ __builtin_clz(x)` for a positive 32-bit `x` is
//! `(31 - x.leading_zeros()) as i32`.

/// `31 ^ __builtin_clz(x)` for `x >= 1`.
fn clz_log2(x: u32) -> i32 {
    (31 - x.leading_zeros()) as i32
}

/// Extra bits for a distance, matching `ZopfliGetDistExtraBits`.
pub fn dist_extra_bits(dist: i32) -> i32 {
    if dist < 5 {
        return 0;
    }
    clz_log2((dist - 1) as u32) - 1
}

/// Extra-bits value for a distance, matching `ZopfliGetDistExtraBitsValue`.
pub fn dist_extra_bits_value(dist: i32) -> i32 {
    if dist < 5 {
        0
    } else {
        let l = clz_log2((dist - 1) as u32);
        (dist - (1 + (1 << l))) & ((1 << (l - 1)) - 1)
    }
}

/// Distance symbol, matching `ZopfliGetDistSymbol`.
pub fn dist_symbol(dist: i32) -> i32 {
    if dist < 5 {
        dist - 1
    } else {
        let l = clz_log2((dist - 1) as u32);
        let r = ((dist - 1) >> (l - 1)) & 1;
        l * 2 + r
    }
}

